// REPORTS GENERATION
// ==========================================

const getReports = async (req, res, next) => {
  try {
    const { period = 'daily', format = 'json' } = req.query;

    const startDate = new Date();
    if (period === 'daily') {
      startDate.setHours(0, 0, 0, 0);
    } else if (period === 'weekly') {
      startDate.setDate(startDate.getDate() - 7);
    } else if (period === 'monthly') {
      startDate.setMonth(startDate.getMonth() - 1);
    }

    const tokens = await Token.find({ generatedAt: { $gte: startDate } })
      .populate('officeId', 'name code city')
      .populate('departmentId', 'name')
      .populate('serviceId', 'name code')
      .populate('counterId', 'counterNumber')
      .sort({ generatedAt: -1 });

    if (format === 'csv') {
      // Generate CSV string
      const headers = 'Token,Citizen,Office,Department,Service,Counter,Status,WaitMinutes,DurationMinutes,GeneratedAt,CompletedAt\n';
      const rows = tokens
        .map((t) => {
          return `"${t.tokenNumber}","${t.citizenName}","${t.officeId?.name || ''}","${t.departmentId?.name || ''}","${t.serviceId?.name || ''}","${t.counterId?.counterNumber || ''}","${t.status}","${t.estimatedWaitTime}","${t.serviceDurationMinutes || 0}","${t.generatedAt?.toISOString() || ''}","${t.completedAt?.toISOString() || ''}"`;
        })
        .join('\n');

      res.setHeader('Content-Type', 'text/csv');
      res.setHeader('Content-Disposition', `attachment; filename="queueless_report_${period}.csv"`);
      return res.status(200).send(headers + rows);
    }

    res.status(200).json({
      success: true,
      period,
      count: tokens.length,
      tokens,
    });
  } catch (err) {
    next(err);
  }
};

