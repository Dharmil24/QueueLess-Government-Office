const sanitizeDocuments = (docs) => {
  if (!docs) return [];
  if (Array.isArray(docs)) {
    return docs
      .map((d) => (typeof d === 'string' ? d.trim() : ''))
      .filter((d) => Boolean(d));
  }
  if (typeof docs === 'string') {
    return docs
      .split(/[\n,]+/)
      .map((d) => d.trim())
      .filter((d) => Boolean(d));
  }
  return [];
};

