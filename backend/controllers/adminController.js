const updateLiveToken = async (req, res, next) => {
  try {
    const { id } = req.params;
    const { priority, status, counterId, notes, estimatedWaitTime } = req.body;
    const updateData = {};
    if (priority) updateData.priority = priority;
    if (status) updateData.status = status;
    if (counterId !== undefined) updateData.counterId = counterId || null;
    if (notes !== undefined) updateData.notes = notes;
    if (estimatedWaitTime !== undefined) updateData.estimatedWaitTime = estimatedWaitTime;

    const token = await Token.findByIdAndUpdate(id, updateData, { new: true })
      .populate('officeId', 'name code')
      .populate('serviceId', 'name code')
      .populate('counterId', 'counterNumber');

    if (!token) return res.status(404).json({ success: false, message: 'Token not found' });

    const { recalculateQueue } = require('../services/queueService');
    await recalculateQueue(token.officeId._id, token.serviceId._id);

    const { emitToUser, emitToOffice } = require('../sockets/socketHandler');
    emitToUser(token.citizenId.toString(), 'token_updated', token);
    emitToOffice(token.officeId._id.toString(), 'queue_updated', { officeId: token.officeId._id });

    res.status(200).json({ success: true, token });
  } catch (err) {
    next(err);
  }
};

const deleteLiveToken = async (req, res, next) => {
  try {
    const { id } = req.params;
    const token = await Token.findById(id);
    if (!token) return res.status(404).json({ success: false, message: 'Token not found' });

    token.status = 'CANCELLED';
    token.cancelledAt = new Date();
    await token.save();

    const { recalculateQueue } = require('../services/queueService');
    await recalculateQueue(token.officeId, token.serviceId);

    const { emitToUser, emitToOffice } = require('../sockets/socketHandler');
    emitToUser(token.citizenId.toString(), 'token_cancelled', { tokenId: token._id, tokenNumber: token.tokenNumber });
    emitToOffice(token.officeId.toString(), 'queue_updated', { officeId: token.officeId });

    res.status(200).json({ success: true, message: 'Token cancelled successfully from queue' });
  } catch (err) {
    next(err);
  }
};

